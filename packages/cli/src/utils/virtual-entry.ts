/**
 * Generate the in-memory virtual entrypoint source for Bun.build(). Static
 * imports let the bundler trace and embed all route modules.
 *
 * Each route directory is self-contained — no global tier hooks; groups
 * only affect URL stripping.
 */

import type { BuildConfig, RuntimeTarget } from '../types/index';
import type {
    ApiRouteScanEntry,
    PageRouteScanEntry,
    WebSocketRouteScanEntry,
    AssetRouteScanEntry,
} from './scanner';
import { readFileSync } from 'fs';

/** Paths to app-level convention files for production builds. */
export interface AppConventionPaths {
    /** Path to `src/hooks.ts` — exports all 6 hook points */
    hooksPath?: string;
    /** Path to `src/plugins.ts` — default export: (burger: PluginRegistrar) => void */
    pluginsPath?: string;
    /** Path to `src/providers.ts` — default export: (burger: ProviderRegistrar) => void */
    providersPath?: string;
    /** Path to `src/openapi.config.ts` — default export: OpenAPIConfig */
    openapiConfigPath?: string;
}

function pushImportLines(
    lines: string[],
    entries: { importPath: string }[],
    variablePrefix: 'r' | 'p'
): void {
    entries.forEach((entry, index) => {
        lines.push(
            `import * as _${variablePrefix}${index} from '${entry.importPath}';`
        );
    });
}

/**
 * Generate virtual entrypoint source that imports all routes and starts Burger with apiRoutes/pageRoutes.
 */
export function generateVirtualEntrySource(
    config: BuildConfig,
    apiEntries: ApiRouteScanEntry[],
    pageEntries: PageRouteScanEntry[],
    optionsImportPath?: string,
    appConventions?: AppConventionPaths,
    wsEntries: WebSocketRouteScanEntry[] = [],
    assetEntries: AssetRouteScanEntry[] = [],
    /**
     * Import BunAdapter statically and inject it via ServerOptions.adapter.
     * Defaults to the bun target: a bun bundle is a self-contained file with
     * no node_modules alongside it, and Bun cannot embed the adapter
     * loader's computed dynamic import. WinterCG targets pass false — their
     * bundles must not pull in the Bun adapter — and so does the
     * `--target=browser` passthrough (client code).
     */
    bundleBunAdapter?: boolean,
    target: RuntimeTarget = 'bun'
): string {
    const lines: string[] = [];
    const isPortableTarget =
        target === 'cloudflare' || target === 'deno' || target === 'vercel';
    const isBunBundle = bundleBunAdapter ?? target === 'bun';

    lines.push('// Auto-generated by burger-api build. Do not edit.');
    lines.push("import { Burger } from 'burger-api';");
    if (isPortableTarget) {
        lines.push("import { toFetchHandler } from 'burger-api';");
    } else if (target === 'node') {
        lines.push("import { serve } from '@burger-api/node-server';");
    }
    if (isBunBundle) {
        // The adapter loader resolves `burger-api/adapter/bun` through a
        // computed specifier so WinterCG bundles never pull in `import 'bun'`.
        // A bun bundle (and a `--compile` binary) has no node_modules at
        // runtime, and Bun cannot embed that computed import, so import the
        // adapter statically here and inject it via ServerOptions.adapter.
        lines.push(
            "import { BunAdapter as __BunAdapter } from 'burger-api/adapter/bun';"
        );
    }
    if (optionsImportPath) {
        lines.push(
            `import { burgerOptions as __burgerOptions } from '${optionsImportPath}';`
        );
    }
    lines.push('');
    if (target === 'bun') {
        // Make CWD the bundle directory so HTML chunk paths resolve.
        // `import.meta.dir` is Bun-only: portable targets have no
        // filesystem-relative chunks and Node would throw on it.
        lines.push('process.chdir(import.meta.dir);');
        lines.push('');
    }

    pushImportLines(lines, apiEntries, 'r');
    if (pageEntries.length) {
        lines.push('');
        pushImportLines(lines, pageEntries, 'p');
    }

    // Import WebSocket route modules and siblings — otherwise file-based
    // ws.ts routes are silently dropped from production builds (they exist
    // only in the dev filesystem scan).
    if (wsEntries.length) {
        lines.push('');
        wsEntries.forEach((w, i) => {
            lines.push(`import * as _w${i} from '${w.importPath}';`);
            if (w.hooksPath) {
                lines.push(`import * as _wh${i} from '${w.hooksPath}';`);
            }
            if (w.configPath) {
                lines.push(`import * as _wc${i} from '${w.configPath}';`);
            }
        });
    }

    // Import sibling hooks files; each route is self-contained (no global
    // tier merging).
    apiEntries.forEach((e, i) => {
        if (e.hooksPath) {
            lines.push(`import * as _h${i} from '${e.hooksPath}';`);
        }
    });

    // Import per-route schema/openapi/config files for build-time merging.
    apiEntries.forEach((e, i) => {
        if (e.schemaPath) {
            lines.push(`import * as _s${i} from '${e.schemaPath}';`);
        }
        if (e.openapiPath) {
            lines.push(`import * as _o${i} from '${e.openapiPath}';`);
        }
        if (e.configPath) {
            lines.push(`import * as _c${i} from '${e.configPath}';`);
        }
    });
    // Handlers and convention exports are read from module namespaces at
    // startup, never guessed from source text, so every export style
    // behaves as in dev. Optional exports go through a helper so bundlers
    // (wrangler, esbuild) don't warn about legitimately undefined imports.
    if (apiEntries.length || wsEntries.length) {
        lines.push('');
        lines.push('function __mod(mod) {');
        lines.push(' return mod.default ?? mod;');
        lines.push('}');
        lines.push('function __get(mod, key) {');
        lines.push(' return mod[key];');
        lines.push('}');
        lines.push('function __pick(mod, keys) {');
        lines.push(' const out = {};');
        lines.push(' for (const k of keys) {');
        lines.push("  if (typeof mod[k] === 'function') out[k] = mod[k];");
        lines.push(' }');
        lines.push(' return out;');
        lines.push('}');
    }
    if (apiEntries.length) {
        // The framework adds its own OPTIONS handler (204 + Allow) and skips
        // beforeRoute for it — emitting one here would bypass that.
        lines.push('function __handlers(mod) {');
        lines.push(
            " return __pick(mod, ['GET', 'POST', 'PUT', 'DELETE', 'PATCH', 'HEAD', 'OPTIONS']);"
        );
        lines.push('}');
        lines.push('function __normOpenapi(mod) {');
        lines.push(' if (!mod) return mod;');
        lines.push(' const out = {};');
        lines.push(' for (const k of Object.keys(mod)) {');
        lines.push(
            ' out[/^(GET|POST|PUT|DELETE|PATCH|HEAD|OPTIONS)$/.test(k) ? k.toLowerCase() : k] = mod[k];'
        );
        lines.push(' }');
        lines.push(' return out;');
        lines.push('}');
        // config.ts mixes a route-wide default export with per-method named
        // exports (e.g. `export const POST = {...}`); keep both so the
        // framework can merge the method overrides at startup.
        lines.push('function __config(mod) {');
        lines.push(' if (!mod) return mod;');
        lines.push(
            ' if (mod.default === undefined || mod.default === null || typeof mod.default !== "object") return __mod(mod);'
        );
        lines.push(' let out = mod.default;');
        lines.push(' for (const k of Object.keys(mod)) {');
        lines.push(
            '  if (/^(GET|POST|PUT|DELETE|PATCH|HEAD|OPTIONS)$/.test(k)) {'
        );
        lines.push('   if (out === mod.default) out = { ...out };');
        lines.push('   out[k] = mod[k];');
        lines.push('  }');
        lines.push(' }');
        lines.push(' return out;');
        lines.push('}');
    }
    // HTML pages load as raw strings (bun.ts `.html` loader, like dev's
    // `?raw` import), but Bun.serve accepts only functions/HTMLBundles/
    // Responses — wrap string defaults in a text/html Response factory.
    if (pageEntries.length) {
        lines.push('function __page(mod) {');
        lines.push(' const h = mod.default;');
        lines.push(" if (typeof h === 'function') return h;");
        lines.push(
            " return () => new Response(h, { headers: { 'Content-Type': 'text/html; charset=utf-8' } });"
        );
        lines.push('}');
    }

    // Import app-level convention files for production builds
    if (appConventions) {
        if (appConventions.hooksPath) {
            lines.push(
                `import * as __globalHooks from '${appConventions.hooksPath}';`
            );
        }
        if (appConventions.pluginsPath) {
            lines.push(
                `import * as __pluginsModule from '${appConventions.pluginsPath}';`
            );
        }
        if (appConventions.providersPath) {
            lines.push(
                `import * as __providersModule from '${appConventions.providersPath}';`
            );
        }
        if (appConventions.openapiConfigPath) {
            lines.push(
                `import __openapiConfig from '${appConventions.openapiConfigPath}';`
            );
        }
    }

    lines.push('');
    lines.push('const apiRoutes = [');

    apiEntries.forEach((e, i) => {
        lines.push(' {');
        lines.push(` path: ${JSON.stringify(e.routePath)},`);
        lines.push(` handlers: __handlers(_r${i}),`);
        lines.push(
            ` schema: ${e.schemaPath ? `__mod(_s${i})` : `__get(_r${i}, 'schema')`},`
        );
        lines.push(
            ` openapi: ${e.openapiPath ? `__normOpenapi(__mod(_o${i}))` : `__get(_r${i}, 'openapi')`},`
        );
        lines.push(
            ` config: ${e.configPath ? `__config(_c${i})` : `__get(_r${i}, 'config')`},`
        );
        lines.push(
            ` hooks: ${e.hooksPath ? `__mod(_h${i})` : `__get(_r${i}, 'hooks')`},`
        );
        lines.push(` isWildcard: ${e.isWildcard},`);
        lines.push(' },');
    });

    lines.push('];');
    lines.push('');

    lines.push('const pageRoutes = [');
    pageEntries.forEach((p, i) => {
        lines.push(
            ` { path: ${JSON.stringify(p.routePath)}, handler: __page(_p${i}) },`
        );
        if (p.routePath !== '/' && !p.routePath.endsWith('/')) {
            lines.push(
                ` { path: ${JSON.stringify(p.routePath + '/')}, handler: __page(_p${i}) },`
            );
        }
    });
    lines.push('];');
    lines.push('');

    if (wsEntries.length) {
        lines.push('const wsRoutes = [');
        wsEntries.forEach((w, i) => {
            lines.push(' {');
            lines.push(` path: ${JSON.stringify(w.routePath)},`);
            lines.push(
                ` handlers: __pick(_w${i}, ['open', 'message', 'close', 'drain', 'ping', 'pong']),`
            );
            if (w.hooksPath) {
                lines.push(
                    ` hooks: __pick(_wh${i}, ['onOpen', 'onMessage', 'onClose']),`
                );
            }
            if (w.configPath) {
                lines.push(` config: __mod(_wc${i}),`);
            }
            lines.push(' },');
        });
        lines.push('];');
        lines.push('');
    }

    lines.push('const app = new Burger({');
    // Declares the deployment target so WebSocket upgrade handling can trust
    // it over `globalThis` detection (Node vs. Vercel are indistinguishable
    // at request time).
    lines.push(` runtimeTarget: ${JSON.stringify(target)},`);
    if (isBunBundle) {
        // Emitted before user options so an explicit `adapter` in
        // burgerOptions.ts still wins (last key wins).
        lines.push(' adapter: new __BunAdapter(),');
    }
    // Always explicit so an unbundled production entry (deno, vercel,
    // wrangler dev) never falls back to dev-mode error output; an explicit
    // `debug` in the entry options still wins (spread last).
    lines.push(` debug: ${config.debug === true},`);
    if (optionsImportPath) {
        lines.push(' ...__burgerOptions,');
    }
    if (appConventions?.hooksPath) {
        lines.push(' globalHooks: __globalHooks,');
    }
    if (appConventions?.pluginsPath) {
        lines.push(' pluginsModule: __pluginsModule,');
    }
    if (appConventions?.providersPath) {
        lines.push(' providersModule: __providersModule,');
    }
    if (appConventions?.openapiConfigPath) {
        lines.push(' openapi: __openapiConfig,');
    }
    lines.push(' apiRoutes,');
    lines.push(' pageRoutes,');
    if (wsEntries.length) {
        lines.push(' wsRoutes,');
    }
    if (assetEntries.length) {
        // Assets are base64-embedded at build time so the bundle stays
        // self-contained (no filesystem access at runtime).
        lines.push(' assetRoutes: [');
        for (const asset of assetEntries) {
            const data = readFileSync(asset.absolutePath).toString('base64');
            lines.push(
                `  { path: ${JSON.stringify(asset.routePath)}, contentType: ${JSON.stringify(asset.contentType)}, data: ${JSON.stringify(data)} },`
            );
        }
        lines.push(' ],');
    }
    lines.push('});');
    lines.push('');
    if (isPortableTarget) {
        // Cloudflare/Deno/Vercel: no long-running process to bind a port to —
        // the platform calls `fetch` per request and its own tool bundles
        // this file (Bun.build never runs for this target).
        if (target === 'vercel') {
            // Without this, Vercel defaults to the Edge runtime, which
            // rejects the plain `export default { fetch }` shape.
            lines.push("export const runtime = 'nodejs';");
            lines.push('');
        }
        lines.push('export default { fetch: toFetchHandler(app) };');
    } else if (target === 'node') {
        lines.push('const port = Number(process.env.PORT) || 4000;');
        lines.push('serve(app, { port });');
        lines.push('console.log(`Server running on http://localhost:${port}`);');
    } else {
        lines.push('const port = Number(process.env.PORT) || 4000;');
        lines.push('app.serve(port, () => {');
        lines.push(
            ' console.log(`Server running on http://localhost:${port}`);'
        );
        lines.push('});');
    }

    return lines.join('\n');
}
